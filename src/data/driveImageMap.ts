export function resolveGoogleDriveAsset(url?: string): string | undefined {
  if (!url) return undefined;
  if (!url.includes('drive.google.com/file/d/')) return url;
  const match = url.match(/\/d\/([a-zA-Z0-9_-]+)/);
  if (match && match[1]) {
    const id = match[1];
    if (googleDriveLocalAssetMap[id]) {
      return googleDriveLocalAssetMap[id];
    }
    for (const [key, localPath] of Object.entries(googleDriveLocalAssetMap)) {
      if (id.includes(key) || key.includes(id)) {
        return localPath;
      }
    }
    return `https://lh3.googleusercontent.com/d/${id}`;
  }
  return url;
}
